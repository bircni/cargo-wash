#!/usr/bin/env bash
#
# Renders the Homebrew formula for a release to stdout. The release workflow commits the
# result to bircni/homebrew-tap as Formula/cargo-wash.rb.
#
# Usage: scripts/homebrew_formula.sh <version> <directory holding the release archives>
#
# The version doubles as the tag name, which is how release_version.ps1 tags releases.

set -euo pipefail

# Function to print errors only
err() { echo "$@" 1>&2; }

if [ $# -ne 2 ]; then
    err "Usage: $0 <version> <archive directory>"
    exit 1
fi

version="$1"
archives="$2"
download="https://github.com/bircni/cargo-wash/releases/download/${version}"

# Prints the SHA-256 of the archive built for the given target.
checksum() {
    local archive="${archives}/cargo-wash-${version}-$1.tar.gz"
    if [ ! -f "$archive" ]; then
        err "Missing release archive: $archive"
        exit 1
    fi
    shasum -a 256 "$archive" | cut -d' ' -f1
}

# Resolved before rendering: a failure inside the heredoc would not stop the script.
sha_macos_arm=$(checksum aarch64-apple-darwin)
sha_macos_intel=$(checksum x86_64-apple-darwin)
sha_linux_intel=$(checksum x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew_formula.sh in bircni/cargo-wash on every release.
# Changes made here are overwritten by the next release.
class CargoWash < Formula
  desc "Clean up the target folders of all your Cargo projects"
  homepage "https://github.com/bircni/cargo-wash"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "${download}/cargo-wash-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${sha_macos_arm}"
    end
    on_intel do
      url "${download}/cargo-wash-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${sha_macos_intel}"
    end
  end

  on_linux do
    # Only an x86_64 build is published for Linux.
    depends_on arch: :x86_64

    on_intel do
      url "${download}/cargo-wash-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${sha_linux_intel}"
    end
  end

  def install
    bin.install "cargo-wash"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/cargo-wash --version")

    (testpath/"scan").mkpath
    output = shell_output("#{bin}/cargo-wash stats --json --path #{testpath}/scan")
    assert_equal({ "projects" => [], "total_size" => 0 }, JSON.parse(output))
  end
end
EOF
